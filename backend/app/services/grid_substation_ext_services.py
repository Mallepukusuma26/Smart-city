class GridSubstationExtService1:
    @staticmethod
    def evaluate_metric(alpha, beta, gamma):
        """Calculates domain metric index."""
        idx = (alpha * 0.5) + (beta * 0.3) + (gamma * 0.2)
        return {
            "metric_index": round(idx, 2),
            "status": "EXCELLENT" if idx >= 80.0 else "OPERATIONAL"
        }

